import { createHash } from "node:crypto";
import {
    existsSync,
    readFileSync,
    statSync,
    writeFileSync,
} from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const projectRoot = dirname(dirname(fileURLToPath(import.meta.url)));
const runtimeFile = "ort-wasm-simd-threaded.wasm";

function resolveOnnxRuntimeRoot() {
    const transformersRequire = createRequire(require.resolve("@huggingface/transformers"));
    let current = dirname(transformersRequire.resolve("onnxruntime-web/wasm"));
    for (let depth = 0; depth < 8; depth += 1) {
        if (existsSync(join(current, "package.json")) && existsSync(join(current, "dist"))) {
            return current;
        }
        const parent = dirname(current);
        if (parent === current) break;
        current = parent;
    }
    throw new Error("Unable to resolve the installed onnxruntime-web package root.");
}

function sha256(path) {
    return createHash("sha256").update(readFileSync(path)).digest("hex");
}

const runtimeRoot = resolveOnnxRuntimeRoot();
const runtimePackage = JSON.parse(readFileSync(join(runtimeRoot, "package.json"), "utf8"));
const runtimePath = join(runtimeRoot, "dist", runtimeFile);
if (!existsSync(runtimePath)) {
    throw new Error(`Expected ONNX Runtime asset is missing: ${runtimePath}`);
}

const version = String(runtimePackage.version);
const bytes = statSync(runtimePath).size;
const digest = sha256(runtimePath);
const cdnPath = `onnxruntime-web@${version}/dist/${runtimeFile}`;
const policyId = `onnxruntime-web-${version}-wasm-v1`;
const output = `// AUTO-GENERATED by scripts/generate-local-ai-runtime-policy.mjs.
// The runtime identity follows the exact onnxruntime-web build resolved from package-lock.json.
import type { LocalAiRuntimePolicy } from "../../domain/local-ai/local-ai-runtime-assets";

export const BUILTIN_ORT_RUNTIME_POLICY = ${JSON.stringify({
    id: policyId,
    engine: "onnxruntime-web",
    version,
    backend: "wasm",
    cacheName: "vault-coach-local-ai-runtime-v1",
    artifact: {
        file: runtimeFile,
        urls: [
            `https://cdn.jsdelivr.net/npm/${cdnPath}`,
            `https://unpkg.com/${cdnPath}`,
        ],
        bytes,
        sha256: digest,
        mediaType: "application/wasm",
    },
}, null, 4)} as const satisfies LocalAiRuntimePolicy;
`;

const target = join(projectRoot, "src", "app", "local-ai", "runtime-registry.ts");
const previous = existsSync(target) ? readFileSync(target, "utf8") : "";
if (previous !== output) writeFileSync(target, output);

console.log(`Pinned ${runtimePackage.name}@${version} ${runtimeFile} (${bytes} bytes, sha256 ${digest}).`);
